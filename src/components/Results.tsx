import { Copy, Trash2, Plus } from "lucide-react";
import { toast } from "sonner";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Checkbox } from "@/components/ui/checkbox";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { STATUSES, type ActionItem, type MeetingInsights } from "@/lib/meeting-schema";

async function copy(text: string, label: string) {
  try {
    await navigator.clipboard.writeText(text);
    toast.success(`${label} copied`);
  } catch {
    toast.error(`Couldn't copy ${label.toLowerCase()} — select and copy manually.`);
  }
}

function List({ items, empty }: { items: string[]; empty: string }) {
  if (!items.length) return <p className="text-sm text-muted-foreground">{empty}</p>;
  return (
    <ul className="space-y-2">
      {items.map((t, i) => (
        <li key={i} className="flex gap-3 text-sm leading-relaxed">
          <span className="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-primary" />
          {t}
        </li>
      ))}
    </ul>
  );
}

export function Results({ value, onChange }: { value: MeetingInsights; onChange: (v: MeetingInsights) => void }) {
  const items = value.actionItems;
  const setItem = (id: string, patch: Partial<ActionItem>) =>
    onChange({ ...value, actionItems: items.map((a) => (a.id === id ? { ...a, ...patch } : a)) });

  const summaryText = [
    value.summary,
    value.keyPoints.length ? `\nKey points:\n${value.keyPoints.map((k) => `- ${k}`).join("\n")}` : "",
    value.decisions.length ? `\nDecisions:\n${value.decisions.map((k) => `- ${k}`).join("\n")}` : "",
    value.openQuestions.length ? `\nOpen questions:\n${value.openQuestions.map((k) => `- ${k}`).join("\n")}` : "",
  ].join("\n");
  const done = items.filter((a) => a.status === "Completed").length;

  return (
    <div>
      <div className="mb-4 flex items-baseline justify-between">
        <h2 className="text-4xl">Meeting insights</h2>
        <span className="text-xs text-muted-foreground">Generated by AI from your transcript — review before sharing</span>
      </div>
      <Tabs defaultValue="summary">
        <TabsList className="flex-wrap">
          <TabsTrigger value="summary">Summary</TabsTrigger>
          <TabsTrigger value="decisions">Decisions ({value.decisions.length})</TabsTrigger>
          <TabsTrigger value="actions">Action items ({items.length})</TabsTrigger>
          <TabsTrigger value="email">Follow-up email</TabsTrigger>
        </TabsList>

        <div className="mt-4 rounded-lg border border-border bg-card p-6 shadow-[var(--shadow-paper)]">
          <TabsContent value="summary" className="mt-0 space-y-6">
            <div className="flex items-start justify-between gap-4">
              <p className="max-w-3xl text-lg leading-relaxed">{value.summary}</p>
              <Button variant="outline" size="sm" onClick={() => copy(summaryText, "Summary")}>
                <Copy /> Copy summary
              </Button>
            </div>
            <div className="grid gap-6 md:grid-cols-2">
              <div>
                <h3 className="mb-3 text-2xl">Key points</h3>
                <List items={value.keyPoints} empty="No key points identified." />
              </div>
              <div>
                <h3 className="mb-3 text-2xl">Open questions</h3>
                <List items={value.openQuestions} empty="No open questions." />
              </div>
            </div>
          </TabsContent>

          <TabsContent value="decisions" className="mt-0">
            <List items={value.decisions} empty="No confirmed decisions were found in this meeting." />
          </TabsContent>

          <TabsContent value="actions" className="mt-0">
            <div className="mb-3 flex items-center justify-between">
              <p className="text-sm text-muted-foreground">
                {items.length ? `${done} of ${items.length} completed` : "No action items were found in this meeting."}
              </p>
              <Button
                variant="outline"
                size="sm"
                onClick={() =>
                  onChange({
                    ...value,
                    actionItems: [
                      ...items,
                      { id: `${Date.now()}`, task: "", owner: "Unassigned", deadline: "Not specified", priority: "Not specified", status: "Pending", evidence: "" },
                    ],
                  })
                }
              >
                <Plus /> Add task
              </Button>
            </div>
            <div className="space-y-3">
              {items.map((a) => (
                <div key={a.id} className={`rounded-md border border-border p-4 ${a.status === "Completed" ? "bg-muted opacity-75" : "bg-background"}`}>
                  <div className="flex items-start gap-3">
                    <Checkbox
                      className="mt-2.5"
                      aria-label={`Mark "${a.task || "task"}" complete`}
                      checked={a.status === "Completed"}
                      onCheckedChange={(c) => setItem(a.id, { status: c ? "Completed" : "Pending" })}
                    />
                    <div className="grid flex-1 gap-2 md:grid-cols-[1fr_150px_150px_140px]">
                      <Input aria-label="Task" value={a.task} placeholder="Task" onChange={(e) => setItem(a.id, { task: e.target.value })} className={a.status === "Completed" ? "line-through" : ""} />
                      <Input aria-label="Owner" value={a.owner} onChange={(e) => setItem(a.id, { owner: e.target.value })} className={a.owner === "Unassigned" ? "italic text-muted-foreground" : ""} />
                      <Input aria-label="Deadline" value={a.deadline} onChange={(e) => setItem(a.id, { deadline: e.target.value })} className={a.deadline === "Not specified" ? "italic text-muted-foreground" : ""} />
                      <Select value={a.status} onValueChange={(v) => setItem(a.id, { status: v as ActionItem["status"] })}>
                        <SelectTrigger aria-label="Status"><SelectValue /></SelectTrigger>
                        <SelectContent>
                          {STATUSES.map((s) => <SelectItem key={s} value={s}>{s}</SelectItem>)}
                        </SelectContent>
                      </Select>
                    </div>
                    <Button variant="ghost" size="icon" aria-label="Delete task" onClick={() => onChange({ ...value, actionItems: items.filter((x) => x.id !== a.id) })}>
                      <Trash2 className="h-4 w-4" />
                    </Button>
                  </div>
                  {(a.evidence || a.priority !== "Not specified") && (
                    <p className="ml-7 mt-2 text-xs text-muted-foreground">
                      {a.priority !== "Not specified" && <span className="mr-2 font-semibold text-accent-foreground">{a.priority} priority</span>}
                      {a.evidence && <>“{a.evidence}”</>}
                    </p>
                  )}
                </div>
              ))}
            </div>
          </TabsContent>

          <TabsContent value="email" className="mt-0 space-y-3">
            <label className="block text-sm font-semibold" htmlFor="email-subject">Subject</label>
            <Input id="email-subject" value={value.email.subject} onChange={(e) => onChange({ ...value, email: { ...value.email, subject: e.target.value } })} />
            <label className="block text-sm font-semibold" htmlFor="email-body">Body</label>
            <Textarea id="email-body" className="min-h-[320px] leading-relaxed" value={value.email.body} onChange={(e) => onChange({ ...value, email: { ...value.email, body: e.target.value } })} />
            <div className="flex flex-wrap gap-2">
              <Button variant="outline" onClick={() => copy(value.email.subject, "Subject")}><Copy /> Copy subject</Button>
              <Button onClick={() => copy(`Subject: ${value.email.subject}\n\n${value.email.body}`, "Email")}><Copy /> Copy email</Button>
            </div>
          </TabsContent>
        </div>
      </Tabs>
    </div>
  );
}
